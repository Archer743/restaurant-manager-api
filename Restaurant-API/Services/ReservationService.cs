    public class ReservationService : IReservationService
    {
        // A collection of characters used for generating the alphanumeric reservation tag
        private readonly string tagChars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
        private readonly int tagLen = 6;

        private readonly ReservationCleanup cleanupSettings;

        private readonly IRoleService roleService;
        private readonly IRestaurantService restaurantService;
        private readonly IShiftService shiftService;

        private readonly IReservationRepo reservationRepo;

        private readonly TimeProvider timeProvider;

		private readonly ILogger<ReservationService> logger;

		public ReservationService(
            IOptions<ReservationCleanup> settings,

            IRoleService roleService,
            IRestaurantService restaurantService,
            IShiftService shiftService,

            IReservationRepo reservationRepo,

            TimeProvider timeProvider,

            ILogger<ReservationService> logger)
        {
            cleanupSettings = settings.Value;

            this.roleService = roleService;
            this.restaurantService = restaurantService;
            this.shiftService = shiftService;

            this.reservationRepo = reservationRepo;

            this.timeProvider = timeProvider;

            this.logger = logger;
		}

        private DateTime UtcNow => timeProvider.GetUtcNow().UtcDateTime;

        public async Task CreateClientReservationAsync(ClientCreateReservationModel createModel)
        {
            // Id is generated by the database
            Reservation reservation = createModel.ToEntity();
            
            reservation.CreatedAtUtc = UtcNow;
            reservation.Tag = await GenerateTagAsync(reservation.RestaurantId);
            reservation.State = ReservationState.Pending;  // Reservation needs to be confirmed by the restaurant

            reservation.Email = reservation.Email == "" ? null : reservation.Email;
            reservation.Phone = reservation.Phone == "" ? null : reservation.Phone;
            reservation.Comment = string.IsNullOrWhiteSpace(reservation.Comment) ? null : reservation.Comment;

            // Validate that the associated restaurant exists
            Restaurant restaurant = await restaurantService.GetByIdAsync(reservation.RestaurantId);

            // Validate reservation start time (must not be in the past)
            if (reservation.StartUtc < UtcNow)
            {
                throw new BadRequestException(ErrorCodes.Data.InvalidDate);
            }

            // Validate that StartUtc is within a restaurant shift
            if (!await shiftService.HasShiftAtTimeAsync(restaurant, reservation.StartUtc))
            {
                throw new BadRequestException(ErrorCodes.Reservation.StartTimeOutsideShift);
            }

            // TODO: Check if the datе is open for reservations

            // Persist reservation
            await reservationRepo.AddAsync(reservation);
        }

        public async Task CreateConfirmedReservationAsync(HttpContext ctx, ReservationCreateModel createModel)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);
            Reservation reservation = createModel.ToEntity();

            reservation.CreatedAtUtc = UtcNow;
            reservation.RestaurantId = currUserRestaurant.Id;
            reservation.Tag = await GenerateTagAsync(currUserRestaurant.Id);
            reservation.State = ReservationState.Confirmed;  // Reservation created by a restaurant member is automatically confirmed
            reservation.IsCreatedByStaff = true;

            reservation.Email = reservation.Email == "" ? null : reservation.Email;
            reservation.Phone = reservation.Phone == "" ? null : reservation.Phone;
            reservation.Comment = string.IsNullOrWhiteSpace(reservation.Comment) ? null : reservation.Comment;

            // Disallow creating a reservation to a past moment unless the user has the Admin role.
            if (reservation.StartUtc < UtcNow && !roleService.HasCurrUserRole(ctx, Roles.Admin))
            {
                throw new ForbiddenException(ErrorCodes.Reservation.CannotCreateInPast);
            }

            // Validate that StartUtc is within a restaurant shift
            if (!await shiftService.HasShiftAtTimeAsync(currUserRestaurant, reservation.StartUtc))
            {
                throw new BadRequestException(ErrorCodes.Reservation.StartTimeOutsideShift);
            }

            // TODO: Check if the datе is open for reservations

            // Persist reservation
            await reservationRepo.AddAsync(reservation);
        }

        public async Task<ReservationViewModel> GetByIdAsync(HttpContext ctx, Guid reservationId)
        {
            // Retrieve the reservation and ensure it belongs to the current user's restaurant
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId);

            return reservation.ToView();
        }

        public async Task<FloorPlanReservationPreviewModel> GetFloorPlanReservationPreviewAsync(HttpContext ctx, Guid reservationId)
        {
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId, includeDetails: true);
            TimeZoneInfo restaurantTimeZone = restaurantService.GetTimeZoneInfo(reservation.Restaurant);

            var preview = reservation.ToFloorPlanPreview(restaurantTimeZone);
            preview.TableCount = reservation.Tables.Count;

            return preview;
        }

        public async Task<List<ReservationCalendarPreviewModel>> GetConfirmedReservationsWithinUtcRangeAsync(HttpContext ctx, UtcRangeQuery query)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // Ensure 'start' date is before 'end' date
            var (startUtc, endUtc) = query.Normalize();

            var reservations =
                await reservationRepo.GetConfirmedWithinUtcRangeAsync(currUserRestaurant.Id, startUtc, endUtc);

            return reservations.Select(r => r.ToCalendarPreview()).ToList();
        }

        public async Task<PagedResult<PendingReservationPreviewModel>> GetPendingReservationsAsync(HttpContext ctx, PendingReservationsQueryParams queryParams)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // At this point, the query is defined but not yet executed against the database
            IQueryable<Reservation> query = reservationRepo.GetPendingReservationsBaseQuery(currUserRestaurant.Id);

            // Apply sorting [Sort by creation time]
            query = queryParams.SortOrder == SortOrder.Asc
                    ? query.OrderBy(r => r.CreatedAtUtc) // (oldest first)
                    : query.OrderByDescending(r => r.CreatedAtUtc); // (newest first)


            int totalItems = await query.CountAsync();
            int totalPages = (int)Math.Ceiling((double)totalItems / queryParams.Limit);

            // Ensuring only the necessary records for the current page are retrieved from the database
            List<Reservation> paginatedReservations = await query
                    .Skip((queryParams.Page - 1) * queryParams.Limit) // Skips records from previous pages
                    .Take(queryParams.Limit) // Takes only the specified number of records for the current page
                    .ToListAsync();

            List<PendingReservationPreviewModel> previewModels = paginatedReservations
                    .Select(r => r.ToPendingPreview())
                    .ToList();

            return new PagedResult<PendingReservationPreviewModel>
            {
                Items = previewModels,
                Pagination = new PaginationMetadata
                {
                    CurrentPage = queryParams.Page,
                    PageSize = queryParams.Limit,
                    TotalItems = totalItems,
                    TotalPages = totalPages
                }
            };
        }

        public async Task CloseReservationAsync(HttpContext ctx, Guid reservationId)
        {
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId, includeDetails: true);

            if (reservation.IsClosed)
            {
                throw new ConflictException(ErrorCodes.Reservation.AlreadyClosed);
            }

            // Mark as closed and remove all reserved tables
            reservation.IsClosed = true;
            reservation.Tables.Clear();

            // Persist changes
            await reservationRepo.UpdateAsync(reservation);
        }

        public async Task ReopenReservationAsync(HttpContext ctx, Guid reservationId)
        {
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId);

            if (!reservation.IsClosed)
            {
                throw new ConflictException(ErrorCodes.Reservation.AlreadyActive);
            }

            reservation.IsClosed = false;
            await reservationRepo.UpdateAsync(reservation);
        }

        public async Task<ReservationViewModel> UpdateAsync(HttpContext ctx, Guid reservationId, ReservationUpdateModel updateModel)
        {
            // Retrieve the reservation and ensure it belongs to the current user's restaurant
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId, includeDetails: true);

            // Track whether any field was actually modified
            bool isModified = false;

            // If the reservation was originally created by a client, core contact details (name, email, phone) cannot be modified
            if (!reservation.IsCreatedByStaff &&
                (updateModel.Name != null || updateModel.Email != null || updateModel.Phone != null))
            {
                throw new ForbiddenException(ErrorCodes.Reservation.CannotModifyClientDetails);
            }

            // Apply name update
            if (!string.IsNullOrEmpty(updateModel.Name) && reservation.Name != updateModel.Name)
            {
                reservation.Name = updateModel.Name;
                isModified = true;
            }

            // Apply StartUtc update
            if (updateModel.StartUtc.HasValue && reservation.StartUtc != updateModel.StartUtc.Value)
            {
                // Disallow moving a reservation to a past date unless the user has the Admin role.
                if (updateModel.StartUtc.Value < UtcNow && !roleService.HasCurrUserRole(ctx, Roles.Admin))
                {
                    throw new ForbiddenException(ErrorCodes.Reservation.CannotModifyToPast);
                }

                // Ensure reservation can be moved to the new shift
                await shiftService.ValidateReservationShiftChangeAsync(reservation, updateModel.StartUtc.Value);

                reservation.StartUtc = updateModel.StartUtc.Value;
                isModified = true;
            }

            // Apply people count update
            if (updateModel.PeopleCount.HasValue && reservation.PeopleCount != updateModel.PeopleCount.Value)
            {
                reservation.PeopleCount = updateModel.PeopleCount.Value;
                isModified = true;
            }

            // Apply email update (passed model validation)
           if (updateModel.Email != null)
            {
                var sanitizedEmail = updateModel.Email == "" ? null : updateModel.Email;

                if (reservation.Email != sanitizedEmail)
                {
                    reservation.Email = sanitizedEmail;
                    isModified = true;
                }
            }

            // Apply phone number update (passed model validation)
            if (updateModel.Phone != null)
            {
                var sanitizedPhone = updateModel.Phone == "" ? null : updateModel.Phone;

                if (reservation.Phone != sanitizedPhone)
                {
                    reservation.Phone = sanitizedPhone;
                    isModified = true;
                }
            }

            // Apply comment update - treat empty or whitespace-only comments as null (i.e., remove the comment)
            if (updateModel.Comment != null)
            {
                var sanitizedComment = string.IsNullOrWhiteSpace(updateModel.Comment) ? null : updateModel.Comment;

                if (reservation.Comment != sanitizedComment)
                {
                    reservation.Comment = sanitizedComment;
                    isModified = true;
                }
            }

            // Persist changes if needed
            if (isModified)
            {
                await reservationRepo.UpdateAsync(reservation);
            }

            // Return the updated reservation to the client
            return reservation.ToView();
        }

