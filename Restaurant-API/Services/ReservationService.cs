        public async Task CleanupReservationsPastRetentionAsync()
        {
			DateTime cutoffUtc = UtcNow.AddMonths(-(int)cleanupSettings.RetentionMonths);

            int removed = await reservationRepo.RemoveReservationsStartedBeforeAsync(cutoffUtc);

            if (removed > 0) logger.LogInformation("Removed {RemovedCount} reservations past retention period!", removed);
		}

        public async Task<Reservation> GetReservationIfOwnedAsync(HttpContext ctx, Guid reservationId, bool includeDetails = false)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // Get reservation by id
            Reservation? reservation = includeDetails ? await reservationRepo.GetByIdWithDetailsAsync(reservationId)
                                                      : await reservationRepo.GetByIdAsync(reservationId);

            // Validate that the user has access to that reservation
            if (reservation == null)
            {
                throw new NotFoundException(ErrorCodes.Reservation.NotFound);
            }
            else if (reservation.RestaurantId != currUserRestaurant.Id)
            {
                throw new ForbiddenException();
            }

            return reservation;
        }


        /* ======================================================================== Private methods */

        // The number of possible combinations is calculated as (number of characters) ^ (tag length).
        // For the current configuration of 36 characters and a length of 6, this results in
        // over 2 billion possible unique combinations (36^6 = 2,176,782,336). This vast
        // number ensures an extremely low probability of collision, making the generation
        // process efficient and reliable.

        // TODO: FIX - set limited tries
        private async Task<string> GenerateTagAsync(Guid restaurantId)
        {
            string tag;
            var random = new Random();
            var buffer = new StringBuilder(tagLen);

            do
            {
                for (int i = 0; i < tagLen; i++)
                {
                    buffer.Append(tagChars[random.Next(tagChars.Length)]);
                }

                tag = buffer.ToString();
                buffer.Clear();
            } while(!await IsTagAvailableAsync(restaurantId, tag));

            return tag;
        }

        private async Task<bool> IsTagAvailableAsync(Guid restaurantId, string tag)
        {
            return (await reservationRepo.GetByTagAsync(restaurantId, tag)) == null;
        }
    }
